% Step 01: Build 15 simulations with native 2 us current-profile logging.
projectFolder = fileparts(mfilename("fullpath"));
model = "GenerateIPMSMCurrentProfile";
load_system(fullfile(projectFolder, model + ".slx"));
initialization = load(fullfile(projectFolder, "Model_Init.mat"));
validateattributes(initialization.PolePairs, {'numeric'}, ...
    {'scalar', 'integer', 'positive', 'finite'});
tables = initialization.optimalTables;
envelopeSpeeds = tables.n_norm(:);
envelopeTorque = tables.TrqEnvelope(:);
assert(numel(envelopeSpeeds) == numel(envelopeTorque) && ...
    all(diff(envelopeSpeeds) > 0) && all(isfinite(envelopeTorque)), ...
    "The torque envelope must have matching, finite data and increasing speeds.");

IPMSM_Sweep_Config = struct( ...
    "ProfileFormatVersion", 2, ...
    "Model", model, ...
    "ModelChecksum", Simulink.getFileChecksum(fullfile(projectFolder, model + ".slx")), ...
    "InitializationChecksum", Simulink.getFileChecksum(fullfile(projectFolder, "Model_Init.mat")), ...
    "Speeds", (1000:1000:15000).', ...
    "TorquePercent", [1, 4:4:100], ...
    "PolePairs", initialization.PolePairs, ...
    "CyclesPerStep", 2, ...
    "ProfileSampleTime", 2e-6, ...
    "SolverSampleTime", initialization.Ts, ...
    "ScopePath", model + "/Scope1");
assert(numel(IPMSM_Sweep_Config.TorquePercent) == 26);
assert(all(IPMSM_Sweep_Config.Speeds >= envelopeSpeeds(1) & ...
    IPMSM_Sweep_Config.Speeds <= envelopeSpeeds(end)), ...
    "All requested speeds must lie within optimalTables.n_norm.");
IPMSM_Sweep_Config.EnvelopeTorque = interp1(envelopeSpeeds, ...
    envelopeTorque, IPMSM_Sweep_Config.Speeds, "linear");
IPMSM_Sweep_Config.TrqCmd = IPMSM_Sweep_Config.EnvelopeTorque * ...
    (IPMSM_Sweep_Config.TorquePercent / 100);
IPMSM_Sweep_Config.ElectricalPeriods = ...
    60 ./ (IPMSM_Sweep_Config.Speeds * IPMSM_Sweep_Config.PolePairs);
IPMSM_Sweep_Config.StopTimes = IPMSM_Sweep_Config.ElectricalPeriods * ...
    IPMSM_Sweep_Config.CyclesPerStep * 26;
IPMSM_Sweep_Config.SamplesPerCycle = IPMSM_Sweep_Config.ElectricalPeriods / ...
    IPMSM_Sweep_Config.ProfileSampleTime;
validateattributes(initialization.Ts, {'numeric'}, {'scalar', 'positive', 'finite'});
sampleRatio = IPMSM_Sweep_Config.ProfileSampleTime / initialization.Ts;
assert(sampleRatio >= 1 && abs(sampleRatio - round(sampleRatio)) < 1e-10, ...
    "The 2 us logging interval must be an integer multiple of the solver step.");
percentAxis = tables.TrqPercent_norm(:);
assert(all(diff(percentAxis) > 0) && ...
    all(IPMSM_Sweep_Config.TorquePercent >= percentAxis(1) & ...
    IPMSM_Sweep_Config.TorquePercent <= percentAxis(end)), ...
    "Torque percentages must lie within the increasing reference-table axis.");
assert(isequal(size(tables.Id_Table), [numel(envelopeSpeeds), numel(percentAxis)]) && ...
    isequal(size(tables.Iq_Table), size(tables.Id_Table)) && ...
    all(isfinite(tables.Id_Table), "all") && all(isfinite(tables.Iq_Table), "all"), ...
    "Reference tables must contain finite speed-by-torque data.");
[percentGrid, speedGrid] = meshgrid(IPMSM_Sweep_Config.TorquePercent, ...
    IPMSM_Sweep_Config.Speeds);
IPMSM_Sweep_Config.Id_ref = interp2(percentAxis, envelopeSpeeds, ...
    tables.Id_Table, percentGrid, speedGrid, "linear");
% Match the controller's positive-torque Iq lookup and tanh(4*TrqCmd) gain.
IPMSM_Sweep_Config.Iq_ref = interp2(percentAxis, envelopeSpeeds, ...
    tables.Iq_Table, percentGrid, speedGrid, "linear") .* ...
    tanh(4 * IPMSM_Sweep_Config.TrqCmd);

ports = find_system(model, "SearchDepth", 1, "BlockType", "Inport");
[~, portOrder] = sort(cellfun(@(p) str2double(get_param(p, "Port")), ports));
ports = ports(portOrder);
portNames = string(cellfun(@(p) get_param(p, "Name"), ports, ...
    "UniformOutput", false));
assert(numel(ports) == 2 && all(ismember(["Speed_rpm", "TrqCmd"], portNames)), ...
    "The model must have the root inports Speed_rpm and TrqCmd.");
scope = get_param(IPMSM_Sweep_Config.ScopePath, "ScopeConfiguration");
assert(scope.DataLogging && scope.DataLoggingVariableName == "IPMSM_Currents", ...
    "Scope1 must already log IPMSM_Currents.");

% Load initialization once into the template so each input is self-contained.
baseInput = Simulink.SimulationInput(model);
variableNames = fieldnames(initialization);
for variableIndex = 1:numel(variableNames)
    name = variableNames{variableIndex};
    baseInput = baseInput.setVariable(name, initialization.(name));
end
baseInput = baseInput.setModelParameter("StartTime", "0");
baseInput = baseInput.setModelParameter("ReturnWorkspaceOutputs", "on");
baseInput = baseInput.setBlockParameter(IPMSM_Sweep_Config.ScopePath, ...
    "DataLoggingSaveFormat", "Structure With Time");
baseInput = baseInput.setBlockParameter(IPMSM_Sweep_Config.ScopePath, ...
    "DataLoggingLimitDataPoints", "off");
baseInput = baseInput.setBlockParameter(IPMSM_Sweep_Config.ScopePath, ...
    "DataLoggingDecimateData", "off");
baseInput = baseInput.setBlockParameter(IPMSM_Sweep_Config.ScopePath, ...
    "SampleTime", sprintf("%.17g", IPMSM_Sweep_Config.ProfileSampleTime));
in = repmat(baseInput, numel(IPMSM_Sweep_Config.Speeds), 1);

for speedIndex = 1:numel(in)
    stepDuration = IPMSM_Sweep_Config.CyclesPerStep * ...
        IPMSM_Sweep_Config.ElectricalPeriods(speedIndex);
    edges = (0:26).' * stepDuration;
    speedSignal = timeseries(repmat(IPMSM_Sweep_Config.Speeds(speedIndex), 2, 1), ...
        [0; edges(end)], "Name", "Speed_rpm");
    speedSignal = setinterpmethod(speedSignal, "zoh");
    torqueValues = IPMSM_Sweep_Config.TrqCmd(speedIndex, :).';
    torqueSignal = timeseries([torqueValues; torqueValues(end)], edges, ...
        "Name", "TrqCmd");
    torqueSignal = setinterpmethod(torqueSignal, "zoh");
    externalInput = Simulink.SimulationData.Dataset;
    for portIndex = 1:numel(ports)
        if portNames(portIndex) == "Speed_rpm"
            externalInput = externalInput.addElement(speedSignal, "Speed_rpm");
        else
            externalInput = externalInput.addElement(torqueSignal, "TrqCmd");
        end
    end
    in(speedIndex) = in(speedIndex).setExternalInput(externalInput);
    in(speedIndex) = in(speedIndex).setModelParameter("StopTime", ...
        sprintf("%.17g", IPMSM_Sweep_Config.StopTimes(speedIndex)));
end
fprintf("Created %d SimulationInput objects: 26 torque steps per speed.\n", numel(in));
fprintf("Current-profile sampling: 2 us; %.0f samples/cycle at 1000 rpm, %.0f at 15000 rpm.\n", ...
    IPMSM_Sweep_Config.SamplesPerCycle(1), IPMSM_Sweep_Config.SamplesPerCycle(end));
fprintf("StopTime: %.6f s at 1000 rpm; %.6f s at 15000 rpm.\n", ...
    IPMSM_Sweep_Config.StopTimes(1), IPMSM_Sweep_Config.StopTimes(end));
