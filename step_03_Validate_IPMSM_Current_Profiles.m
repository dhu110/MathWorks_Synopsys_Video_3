% Step 03: Validate the saved dataset independently of the simulation workspace.
projectFolder = fileparts(mfilename("fullpath"));
saved = load(fullfile(projectFolder, "IPMSM_Current_Profiles.mat"));
IPMSM_Current_Profiles = saved.IPMSM_Current_Profiles;
configData = load(fullfile(projectFolder, "IPMSM_Sweep_Config.mat"), "IPMSM_Sweep_Config");
config = configData.IPMSM_Sweep_Config;
assert(all(isfield(config, {'ProfileFormatVersion', 'ProfileSampleTime', ...
    'SamplesPerCycle', 'Id_ref', 'Iq_ref', 'SweepMode', 'TorqueStepsPerSpeed', ...
    'TotalOperatingPoints', 'InitialTorques', 'TorqueIncrement'})), ...
    "The saved configuration is obsolete. Run step_02 and choose N for absolute torques.");
assert(strcmp(config.DatasetChecksum, Simulink.getFileChecksum( ...
    fullfile(projectFolder, "IPMSM_Current_Profiles.mat"))), ...
    "The saved dataset must match its validation configuration.");
initialization = load(fullfile(projectFolder, "Model_Init.mat"), "optimalTables", "PolePairs");
assert(strcmp(config.InitializationChecksum, Simulink.getFileChecksum( ...
    fullfile(projectFolder, "Model_Init.mat"))), ...
    "The dataset must correspond to the current initialization data.");
expectedSpeeds = (1000:1000:15000).';
requiredFields = {'Speed_rpm', 'TrqCmd', 'TorquePercent', 'TrqEnvelope', ...
    'Id_ref', 'Iq_ref', 'Ia', 'Ib', 'Ic', 'RotorAngle', 'Time'};
assert(isequal(fieldnames(IPMSM_Current_Profiles), requiredFields(:)), ...
    "The dataset must contain exactly the 11 required fields in order.");
assert(isequal(config.Speeds, expectedSpeeds) && ...
    isequal(config.InitialTorques, [10, 25]) && config.TorqueIncrement == 50 && ...
    config.ProfileFormatVersion == 3 && config.SweepMode == "AbsoluteTorque" && ...
    config.ProfileSampleTime == 2e-6 && ...
    ~isfield(config, "NumSamples") && ...
    config.CyclesPerStep == 2 && config.PolePairs == initialization.PolePairs, ...
    "The sweep configuration does not match the required operating points.");
expectedEnvelope = interp1(initialization.optimalTables.n_norm(:), ...
    initialization.optimalTables.TrqEnvelope(:), expectedSpeeds, "linear");
expectedTorques = cell(numel(expectedSpeeds), 1);
expectedPercent = cell(numel(expectedSpeeds), 1);
expectedId = cell(numel(expectedSpeeds), 1);
expectedIq = cell(numel(expectedSpeeds), 1);
percentAxis = initialization.optimalTables.TrqPercent_norm(:);
for speedIndex = 1:numel(expectedSpeeds)
    envelope = expectedEnvelope(speedIndex);
    candidates = [10, 25, 50:50:envelope];
    expectedTorques{speedIndex} = [candidates(candidates < envelope - 1e-9), envelope];
    percentages = 100 * expectedTorques{speedIndex} / envelope;
    percentages(end) = 100;
    expectedPercent{speedIndex} = percentages;
    lookupPercent = min(max(percentages, percentAxis(1)), percentAxis(end));
    lookupSpeed = repmat(expectedSpeeds(speedIndex), size(lookupPercent));
    expectedId{speedIndex} = interp2(percentAxis, initialization.optimalTables.n_norm(:), ...
        initialization.optimalTables.Id_Table, lookupPercent, lookupSpeed, "linear");
    expectedIq{speedIndex} = interp2(percentAxis, initialization.optimalTables.n_norm(:), ...
        initialization.optimalTables.Iq_Table, lookupPercent, lookupSpeed, "linear") .* ...
        tanh(4 * expectedTorques{speedIndex});
end
expectedStepCounts = cellfun(@numel, expectedTorques);
assert(numel(IPMSM_Current_Profiles) == sum(expectedStepCounts) && ...
    config.TotalOperatingPoints == sum(expectedStepCounts) && ...
    isequal(config.TorqueStepsPerSpeed, expectedStepCounts), ...
    "The operating-point count must match the speed-specific absolute-torque grids.");
assert(all(abs(config.StopTimes - 2*expectedStepCounts.*60./ ...
    (expectedSpeeds*config.PolePairs)) < 1e-12), ...
    "Each run must last two electrical cycles per absolute-torque step.");
assert(all(abs(config.ElectricalPeriods - 60./(expectedSpeeds*config.PolePairs)) < 1e-12) && ...
    all(abs(config.SamplesPerCycle - config.ElectricalPeriods/config.ProfileSampleTime) < 1e-8), ...
    "Cycle periods and nominal sample counts must follow speed and pole-pair count.");
assert(all(abs(config.EnvelopeTorque - expectedEnvelope) < 1e-9), ...
    "Sweep envelope torques must match the initialization tables.");

for speedIndex = 1:numel(expectedSpeeds)
    atSpeed = IPMSM_Current_Profiles([IPMSM_Current_Profiles.Speed_rpm] == expectedSpeeds(speedIndex));
    assert(isequal(config.TrqCmd{speedIndex}, expectedTorques{speedIndex}) && ...
        isequal(config.TorquePercent{speedIndex}, expectedPercent{speedIndex}) && ...
        all(abs(config.Id_ref{speedIndex} - expectedId{speedIndex}) < 1e-9) && ...
        all(abs(config.Iq_ref{speedIndex} - expectedIq{speedIndex}) < 1e-9), ...
        "Sweep torque and reference-current commands must match the initialization tables.");
    assert(numel(atSpeed) == expectedStepCounts(speedIndex) && ...
        all(abs(sort([atSpeed.TrqCmd]) - expectedTorques{speedIndex}) < 1e-9), ...
        "Missing or duplicate torque steps at %d rpm.", expectedSpeeds(speedIndex));
    assert(sum(abs([atSpeed.TrqCmd] - expectedEnvelope(speedIndex)) < 1e-9) == 1, ...
        "Each speed must contain exactly one torque-envelope endpoint.");
end

maximumDurationError = 0;
maximumSampleTimeError = 0;
sampleCounts = zeros(numel(IPMSM_Current_Profiles), 1);
for profileIndex = 1:numel(IPMSM_Current_Profiles)
    profile = IPMSM_Current_Profiles(profileIndex);
    for fieldIndex = 1:6
        validateattributes(profile.(requiredFields{fieldIndex}), {'numeric'}, ...
            {'scalar', 'real', 'finite'});
    end
    speedIndex = find(expectedSpeeds == profile.Speed_rpm, 1);
    assert(~isempty(speedIndex), "Unexpected speed operating point.");
    torqueIndex = find(abs(expectedTorques{speedIndex} - profile.TrqCmd) < 1e-9);
    assert(isscalar(torqueIndex), "Unexpected or ambiguous absolute-torque operating point.");
    expectedTorque = expectedTorques{speedIndex}(torqueIndex);
    assert(abs(profile.TrqCmd - expectedTorque) < 1e-9 && ...
        abs(profile.TorquePercent - expectedPercent{speedIndex}(torqueIndex)) < 1e-9 && ...
        abs(profile.TrqEnvelope - expectedEnvelope(speedIndex)) < 1e-9, ...
        "TrqCmd does not match the torque envelope and percentage.");
    assert(abs(profile.Id_ref - expectedId{speedIndex}(torqueIndex)) < 1e-9 && ...
        abs(profile.Iq_ref - expectedIq{speedIndex}(torqueIndex)) < 1e-9, ...
        "Id_ref and Iq_ref must match the controller's operating-point references.");
    sampleCount = numel(profile.Time);
    sampleCounts(profileIndex) = sampleCount;
    vectorNames = {"Ia", "Ib", "Ic", "RotorAngle", "Time"};
    for vectorIndex = 1:numel(vectorNames)
        values = profile.(vectorNames{vectorIndex});
        assert(isnumeric(values) && isreal(values) && ...
            isequal(size(values), [sampleCount, 1]) && sampleCount >= 2 && all(isfinite(values)), ...
            "Each profile must contain matching finite column vectors.");
    end
    period = 60/(profile.Speed_rpm*config.PolePairs);
    nominalCount = period/config.ProfileSampleTime;
    if abs(nominalCount - round(nominalCount)) < 1e-8
        assert(sampleCount == round(nominalCount), "Incorrect integer samples-per-cycle count.");
    else
        assert(ismember(sampleCount, [floor(nominalCount), ceil(nominalCount)]), ...
            "A noninteger cycle length must retain floor or ceil native samples.");
    end
    sampleTimeError = max(abs(diff(profile.Time) - config.ProfileSampleTime));
    maximumSampleTimeError = max(maximumSampleTimeError, sampleTimeError);
    assert(profile.Time(1) == 0 && all(diff(profile.Time) > 0) && sampleTimeError < 1e-12, ...
        "Profile time must start at zero with fixed 2 us spacing.");
    angularSpeed = 2*pi*profile.Speed_rpm/60;
    assert(profile.RotorAngle(1) == 0 && all(diff(profile.RotorAngle) > 0) && ...
        max(abs(profile.RotorAngle - angularSpeed*profile.Time)) < 1e-7, ...
        "RotorAngle must retain the relative mechanical angle at each native sample.");
    assert(profile.RotorAngle(end) < 2*pi/config.PolePairs + 1e-8, ...
        "A half-open profile must not include a duplicate end-of-cycle sample.");
    durationError = abs(profile.Time(end) + config.ProfileSampleTime - period);
    maximumDurationError = max(maximumDurationError, durationError);
    assert(durationError < config.ProfileSampleTime + 1e-12, ...
        "Profile sample coverage must represent one cycle to within one 2 us interval.");
end

IPMSM_Validation = struct("Passed", true, "OperatingPoints", numel(IPMSM_Current_Profiles), ...
    "Speeds", 15, "TorqueStepsPerSpeed", expectedStepCounts, ...
    "SweepMode", "AbsoluteTorque", "ProfileSampleTime", config.ProfileSampleTime, ...
    "SamplesPerProfile", sampleCounts, "MinimumSamplesPerProfile", min(sampleCounts), ...
    "MaximumSamplesPerProfile", max(sampleCounts), ...
    "MaximumSampleTimeError", maximumSampleTimeError, ...
    "MaximumCycleDurationError", maximumDurationError);
save(fullfile(projectFolder, "IPMSM_Current_Profiles_Validation.mat"), "IPMSM_Validation");
fprintf("PASS: %d operating points, 15 speeds with %d to %d absolute-torque steps, native 2 us sampling.\n", ...
    numel(IPMSM_Current_Profiles), min(expectedStepCounts), max(expectedStepCounts));
fprintf("Samples per electrical cycle: %d to %d, depending on speed.\n", ...
    min(sampleCounts), max(sampleCounts));
fprintf("Maximum cycle-duration error: %.3g s.\n", maximumDurationError);

