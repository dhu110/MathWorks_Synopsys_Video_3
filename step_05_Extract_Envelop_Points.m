% Step 05: Extract 15 full-torque profiles for FEA loss-calculation test runs.
projectFolder = fileparts(mfilename("fullpath"));
savedProfiles = load(fullfile(projectFolder, "IPMSM_Current_Profiles.mat"), ...
    "IPMSM_Current_Profiles");
assert(isfield(savedProfiles, "IPMSM_Current_Profiles") && ...
    isstruct(savedProfiles.IPMSM_Current_Profiles) && ...
    ~isempty(savedProfiles.IPMSM_Current_Profiles), ...
    "Run step_02 first to create IPMSM_Current_Profiles.mat.");
requiredFields = {'Speed_rpm', 'TrqCmd', 'TorquePercent', 'TrqEnvelope', ...
    'Id_ref', 'Iq_ref', 'Ia', 'Ib', 'Ic', 'RotorAngle', 'Time'};
assert(isequal(fieldnames(savedProfiles.IPMSM_Current_Profiles), requiredFields(:)), ...
    "The source profiles must use the 11-field format. Run step_02 and choose N for legacy data.");

% Copy whole profiles so currents, angles, timing and reference commands are retained.
IPMSM_Envelope_Current_Profiles = savedProfiles.IPMSM_Current_Profiles( ...
    [savedProfiles.IPMSM_Current_Profiles.TorquePercent] == 100);
IPMSM_Envelope_Current_Profiles = IPMSM_Envelope_Current_Profiles(:);
[~, envelopeOrder] = sort([IPMSM_Envelope_Current_Profiles.Speed_rpm]);
IPMSM_Envelope_Current_Profiles = IPMSM_Envelope_Current_Profiles(envelopeOrder);
expectedSpeeds = (1000:1000:15000).';
assert(numel(IPMSM_Envelope_Current_Profiles) == numel(expectedSpeeds) && ...
    isequal([IPMSM_Envelope_Current_Profiles.Speed_rpm].', expectedSpeeds), ...
    "Expected exactly one 100%% torque profile at each speed from 1000 to 15000 rpm.");

for profileIndex = 1:numel(IPMSM_Envelope_Current_Profiles)
    profile = IPMSM_Envelope_Current_Profiles(profileIndex);
    assert(isscalar(profile.TrqCmd) && isscalar(profile.TrqEnvelope) && ...
        isfinite(profile.TrqCmd) && isfinite(profile.TrqEnvelope) && ...
        abs(profile.TrqCmd - profile.TrqEnvelope) < 1e-9, ...
        "Each full-torque command must match its torque envelope.");
    sampleCount = numel(profile.Time);
    signalNames = {'Ia', 'Ib', 'Ic', 'RotorAngle', 'Time'};
    for signalIndex = 1:numel(signalNames)
        values = profile.(signalNames{signalIndex});
        assert(isnumeric(values) && isreal(values) && ...
            isequal(size(values), [sampleCount, 1]) && sampleCount >= 2 && ...
            all(isfinite(values)), ...
            "Envelope profile signals must contain matching finite column vectors.");
    end
    assert(profile.Time(1) == 0 && all(abs(diff(profile.Time) - 2e-6) < 1e-12), ...
        "Envelope profiles must retain native 2 us sampling. Regenerate legacy data with step_02.");
end

save(fullfile(projectFolder, "IPMSM_Envelope_Current_Profiles.mat"), ...
    "IPMSM_Envelope_Current_Profiles", "-v7.3");
fprintf("Saved 15 envelope current profiles at 100%% torque for FEA loss-calculation test runs.\n");
fprintf("Speeds: 1000 to 15000 rpm; native 2 us samples retained.\n");
